"""Tindari: the inside of the sanctuary grafted into the Tindari.prj2 of Ed's disk as one more room (BASILICA,
generated by content_tindariinterno.py), and the wad of the key of the excavations added to the level.
Nothing else of the file is touched. usage: tindari_santuario.py <Tindari.prj2> <TindariInterno.prj2> <out>"""
import sys

import prj2
import prj2_patch as P
from prj2_check import Reader

src, gen, dst = sys.argv[1:4]
head, top = P.load(src)
d = dict(top)
rooms, _ = P.chunks(d[b"TeRooms"])
last, names = 0, set()
for c, p in rooms:
    r = Reader(p)
    r.leb(), r.leb()
    it = dict(P.chunks(p[r.s.tell():])[0])
    last = max(last, Reader(it[b"TeI"]).leb())
    names.add(it[b"TeName"].decode())
assert "BASILICA" not in names, "already grafted"
next_id = max(Reader(p).leb() for _, _, p in P.raw_objects(src)) + 1
_, gtop = P.load(gen)
(c, p), = P.chunks(dict(gtop)[b"TeRooms"])[0]
r = Reader(p)
r.leb(), r.leb()
h = p[:r.s.tell()]
items = []
for c2, p2 in P.chunks(p[r.s.tell():])[0]:
    if c2 == b"TeI":
        p2 = prj2.leb(last + 1)
    elif c2 == b"TeObjects":
        obs = []
        for oc, op in P.chunks(p2)[0]:
            rr = Reader(op)
            rr.leb()
            obs.append((oc, prj2.leb(next_id) + op[rr.s.tell():]))
            next_id += 1
        p2 = P.pack(obs)
    items.append((c2, p2))
rooms.append((c, h + P.pack(items)))
sitems, _ = P.chunks(d[b"TeSettings"])
wads, _ = P.chunks(dict(sitems)[b"TeWads"])
if not any(b"CdV_Scavi.wad2" in wp for _, wp in wads):
    wc, wp = [(wc, wp) for wc, wp in wads if b"CdV_Oggetti.wad2" in wp][0]
    wads.append((wc, P.pack([(k, v.replace(b"CdV_Oggetti.wad2", b"CdV_Scavi.wad2")) for k, v in P.chunks(wp)[0]])))
    sitems = [(k, P.pack(wads) if k == b"TeWads" else v) for k, v in sitems]
P.save(dst, head, [(k, P.pack(sitems) if k == b"TeSettings" else P.pack(rooms) if k == b"TeRooms" else v) for k, v in top])
print("BASILICA = room", last + 1, "->", dst)
